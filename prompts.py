# 覆盖率不足该怎么读：两种口径二选一（由 REQUIRED_OBJECTS 决定，见 agents.nodes）
# - 旧口径：证据没覆盖全 → 分解不合理（历史记录靠这句复现 v2.1~v2.3）
COVERAGE_RULE_HINT_LEGACY = (
    '- 若"检索证据统计"显示覆盖率低于 100% 且未被硬性否决规则拦截，'
    '说明证据未同时覆盖比较对象，\n  应判"分解不合理"。')
# - 新口径（v2.4）：证据侧不全只说明"检索不均衡"，判定看**回答**有没有讲清每个对象。
#   否则会出现"答案已经补齐两侧、系统却因为证据覆盖 0% 判分解不合理"的自相矛盾。
COVERAGE_RULE_HINT_ANSWER = (
    '- 若"检索证据统计"显示覆盖率低于 100%，只说明检索到的资料不均衡，'
    '**这不等于分解不合理**：\n'
    '  判定以"回答是否讲清每个必答对象"为准。回答已覆盖全部必答对象 → 可通过；\n'
    '  回答缺某个对象时按缺因分流：\n'
    '  · 证据里**有**该对象的资料（只是回答没写）→ 判"内容不合格"（局部重写即可）；\n'
    '  · 证据里**也没有**该对象（"未覆盖"清单同时出现在证据侧和答案侧）→ 判"证据不足"，'
    '理由写明缺哪个对象，走补检索——重写文本补不出没有的内容。')


