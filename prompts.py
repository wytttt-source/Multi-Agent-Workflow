REFLECTION_PROMPT = """
你是严格的系统检查员。请检查以下关于 '{topic}' 的回答是否合格：
回答内容：{result}
实际检索来源：{sources}
检索证据统计：{evidence_stats}

请以严格的 JSON 格式输出（不要包含 Markdown 标记），包含两个字段：
1. "error_type": 只能是以下四种之一：
   - "通过"：回答合格
   - "内容不合格"：偏题、字数太少、未提供细节等
   - "检索失败"：检索无结果
   - "分解不合理"：主题本身包含多个需要独立回答的子问题，
     单段摘要无法完整覆盖，或证据只覆盖部分对象，需要重新拆解任务
2. "reason": 简短的理由
{composite_check_hint}

【硬性否决规则（优先于一切语义判断）】
- 若"检索证据统计"显示证据 0 条：不得判"通过"，只能判"检索失败"。
- 若回答中"【来源】"缺失，或列出的 URL 不在"实际检索来源"中：不得判"通过"，
  判"内容不合格"，理由注明"来源不可核验/疑似编造"。
- 若回答字数少于 120 字且未声明降级：不得判"通过"。
- 只有同时满足以下三条，才允许判"通过"：
  ① 证据条数 ≥ 1；② 回答含"【来源】"且 URL 可在来源清单中找到；③ 回答字数 ≥ 120。
  
额外检查：
- 回答是否真正围绕主题 '{topic}' 展开？
- 如果回答主要讲的是主题的上位概念，应判"偏题"。
- 若"检索证据统计"里出现 balance 且 balance < 0.5，说明某一比较对象在标题层面
  只出现在少数证据中（偏侧），回答可能对弱侧展开不足，应判"分解不合理"。
- balance 在 0.5~0.8 之间时，结合回答质量综合判断：若弱侧有实质展开则可通过，
  若弱侧只是象征性提及则判"分解不合理"。
- 若"检索证据统计"显示覆盖率低于 100% 且未被硬性否决规则拦截，说明证据未同时覆盖比较对象，
  应判"分解不合理"。
"""


